    /** 把商家名/备注丢进来，返回最可能的分类 id。找不到就返回 other。 */
    fun guess(text: String): String {
        if (text.isBlank()) return "other"
        for (c in DEFAULTS) {
            for (k in c.keys) {
                if (text.contains(k)) return c.id
            }
        }
        return "other"
    }

    fun byId(list: List<Cat>, id: String): Cat =
        list.firstOrNull { it.id == id } ?: DEFAULTS.last()

    fun defaultsJson(): String {
        val arr = JSONArray()
        DEFAULTS.forEach { arr.put(it.toJson()) }
